  /// Fetch top 5 categories from database
  Future<void> fetchCategories() async {
    try {
      final snapshot = await _database.child('news').get();

      if (snapshot.exists) {
        final data = snapshot.value as Map<dynamic, dynamic>;
        final Map<String, int> categoryCount = {};

        // Count category occurrences
        data.forEach((key, value) {
          if (value is Map && value['category'] != null) {
            final category = value['category'] as String;
            categoryCount[category] = (categoryCount[category] ?? 0) + 1;
          }
        });

        // Sort by count and take top 5
        final sortedCategories = categoryCount.entries.toList()
          ..sort((a, b) => b.value.compareTo(a.value));

        availableCategories.value = sortedCategories
            .take(5)
            .map((e) => e.key)
            .toList();
      }
    } catch (e) {
      print('Error fetching categories: $e');
    }
  }

  /// Fetch all categories for suggestions
  Future<void> fetchAllCategories() async {
    try {
      final snapshot = await _database.child('news').get();

      if (snapshot.exists) {
        final data = snapshot.value as Map<dynamic, dynamic>;
        final Set<String> categories = {};

        // Collect all unique categories
        data.forEach((key, value) {
          if (value is Map && value['category'] != null) {
            categories.add(value['category'] as String);
          }
          // Also collect from tags
          if (value is Map && value['tags'] != null) {
            final tags = value['tags'];
            if (tags is List) {
              categories.addAll(tags.map((t) => t.toString()));
            }
          }
        });

        allCategories.value = categories.toList()..sort();
      }
    } catch (e) {
      print('Error fetching all categories: $e');
    }
  }

