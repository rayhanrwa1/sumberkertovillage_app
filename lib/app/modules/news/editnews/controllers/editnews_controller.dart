    }

    if (selectedCategory.value.isEmpty) {
      context.showErrorSnackBar('Kategori tidak boleh kosong');
      return false;
    }

    // Check if there's any media (existing or new)
    final hasMedia =
        bannerImage.value != null ||
        existingBannerUrl.value != null ||
        images.isNotEmpty ||
        existingImageUrls.isNotEmpty ||
        videoFile.value != null ||
        existingVideoUrl.value != null;

    if (!hasMedia && !isEditMode.value) {
      context.showErrorSnackBar('Tambahkan minimal satu media');
      return false;
    }

    return true;
  }

  /// Submit news
  Future<void> submitNews(BuildContext context) async {
    // Set category from input before validation
    setManualCategory();

    // Auto-generate tags if empty
    if (autoGeneratedTags.isEmpty) {
      generateAutoTags();
    }

    if (!_validateForm(context)) return;

    try {
      isUploading.value = true;
      uploadProgress.value = 0.0;

      final userId = _currentUserId;
      if (userId == null) {
        context.showErrorSnackBar('Pengguna tidak terautentikasi');
        isUploading.value = false;
        return;
      }

      // Fetch username from database
      String userName = 'Anonymous';
      try {
        userName = _storage2.read('userName') ?? _storage2.read('name') ?? '';

        if (userName.isEmpty) {
          print('Fetching username from database for userId: $userId');
          final userSnapshot = await _database
              .child('users/$userId/name')
              .get();

          if (userSnapshot.exists && userSnapshot.value != null) {
            userName = userSnapshot.value.toString();
            _storage2.write('userName', userName);
            print('Username fetched from database: $userName');
          } else {
            print('No username found in database, using Anonymous');
            userName = 'Anonymous';
          }
        }
      } catch (e) {
        print('Error fetching username: $e');
        userName = 'Anonymous';
      }

      final timestamp = DateTime.now();

      // Generate news ID
      final newsRef = isEditMode.value
          ? _database.child('news/${editingNews!.id}')
          : _database.child('news').push();

      final newsId = newsRef.key!;

      String? bannerUrl;
      List<String> imageUrls = [];
      String? videoUrl;
      String? videoThumbnailUrl;

      // Handle banner - new upload or existing
      if (bannerImage.value != null) {
        // New banner uploaded
        bannerUrl = await _uploadFile(
          bannerImage.value!,
          'news/banners',
          '${newsId}_banner_${timestamp.millisecondsSinceEpoch}.jpg',
        );
      } else if (existingBannerUrl.value != null) {
        // Keep existing banner
        bannerUrl = existingBannerUrl.value;
      }

      // Handle images - combine existing and new
      // First, add existing images that weren't removed
      imageUrls.addAll(existingImageUrls);

      // Then upload new images
      for (int i = 0; i < images.length; i++) {
        final url = await _uploadFile(
          images[i],
          'news/images',
          '${newsId}_image_${existingImageUrls.length + i}_${timestamp.millisecondsSinceEpoch}.jpg',
        );
        if (url != null) {
          imageUrls.add(url);
        }
      }

      // Handle video - new upload or existing
      if (videoFile.value != null) {
        // New video uploaded
        videoUrl = await _uploadFile(
          videoFile.value!,
          'news/videos',
          '${newsId}_video_${timestamp.millisecondsSinceEpoch}.mp4',
        );

        if (videoThumbnail.value != null) {
          videoThumbnailUrl = await _uploadFile(
            videoThumbnail.value!,
            'news/thumbnails',
            '${newsId}_thumbnail_${timestamp.millisecondsSinceEpoch}.jpg',
          );
        }
      } else if (existingVideoUrl.value != null) {
        // Keep existing video
        videoUrl = existingVideoUrl.value;
        videoThumbnailUrl = existingVideoThumbnailUrl.value;
      }

      // Prepare tags - ensure main category is first
      final finalTags = <String>[];
      if (selectedCategory.value.isNotEmpty) {
        finalTags.add(selectedCategory.value);
      }
      for (var tag in autoGeneratedTags) {
        if (!finalTags.contains(tag)) {
          finalTags.add(tag);
        }
      }

      // Create news data with fetched username
      final newsData = {
        'title': titleController.text.trim(),
        'description': descriptionController.text.trim(),
        'created_by': userName,
        'user_id': userId,
        'created_at': isEditMode.value
            ? editingNews!.createdAt.millisecondsSinceEpoch
            : timestamp.millisecondsSinceEpoch,
        'category': selectedCategory.value,
        'tags': finalTags,
        'location': locationController.text.trim().isEmpty
            ? null
            : locationController.text.trim(),
        'banner_image': bannerUrl,
        'images': imageUrls,
        'video_url': videoUrl,
        'video_thumbnail': videoThumbnailUrl,
        'view_count': isEditMode.value ? editingNews!.viewCount : 0,
        'like_count': isEditMode.value ? editingNews!.likeCount : 0,
      };

      print('Saving news with username: $userName');
      print('Tags: $finalTags');

      // Save to Realtime Database
      await newsRef.set(newsData);

      isUploading.value = false;
      uploadProgress.value = 0.0;

      context.showSuccessSnackBar(
        isEditMode.value
            ? 'Berita berhasil diperbarui!'
            : 'Berita berhasil dipublikasikan!',
      );

      // Wait a bit for snackbar to show then navigate
      await Future.delayed(const Duration(milliseconds: 500));

      // Navigate back to news view
      Get.offAllNamed(Routes.NEWS);
    } catch (e) {
      isUploading.value = false;
      uploadProgress.value = 0.0;

      print('Error saving news: $e');
      context.showErrorSnackBar('Gagal menyimpan berita: $e');
    }
  }
