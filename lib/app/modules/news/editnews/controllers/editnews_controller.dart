  /// Extract keywords from text
  List<String> _extractKeywords(String text) {
    // Common Indonesian stop words
    final stopWords = {
      'yang',
      'dan',
      'di',
      'ke',
      'dari',
      'ini',
      'itu',
      'dengan',
