  /// Category search with suggestions
  void _onCategoryChanged() {
    final query = categoryController.text.trim();

    if (query.isEmpty) {
      showCategorySuggestions.value = false;
      categorySuggestions.clear();
      return;
    }

    // Filter categories based on query
    final filtered = allCategories
        .where((cat) => cat.toLowerCase().contains(query.toLowerCase()))
        .toList();

    if (filtered.isNotEmpty) {
      categorySuggestions.value = filtered.take(5).toList();
      showCategorySuggestions.value = true;
    } else {
      categorySuggestions.clear();
      showCategorySuggestions.value = false;
    }

    // Auto-generate tags based on input
    _generateTagsFromText(query);
  }

