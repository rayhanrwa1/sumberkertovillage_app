  Future<void> extractLocationFromImage(File imageFile) async {
    try {
      final bytes = await imageFile.readAsBytes();
      final decoded = img.decodeImage(bytes);
      if (decoded == null) return;

      // Cara baru mengakses EXIF data di image ^4.7.2
      final exifData = decoded.exif;
      if (exifData.isEmpty) return;

      // Akses data GPS menggunakan key langsung
      final latTag = exifData['GPS GPSLatitude'];
      final lonTag = exifData['GPS GPSLongitude'];
      final latRef = exifData['GPS GPSLatitudeRef'];
      final lonRef = exifData['GPS GPSLongitudeRef'];

      if (latTag == null || lonTag == null) return;

      // Parse koordinat
      double? latitude = _parseGpsCoordinate(latTag);
      double? longitude = _parseGpsCoordinate(lonTag);

      if (latitude == null || longitude == null) return;

      // Terapkan referensi arah (N/S/E/W)
      if (latRef != null && latRef.toString().toUpperCase() == 'S') {
        latitude = -latitude;
      }
      if (lonRef != null && lonRef.toString().toUpperCase() == 'W') {
        longitude = -longitude;
      }

      if (_isValidCoordinate(latitude, longitude)) {
        final locationName = _getIndonesiaRegion(latitude, longitude);
        if (locationName != null) {
          locationController.text = locationName;
          detectedLocation.value = locationName;
        }
      }
    } catch (e) {
      print('EXIF extraction error: $e');
    }
  }

  /// Parse GPS coordinate from EXIF format
  double? _parseGpsCoordinate(dynamic gpsData) {
    if (gpsData == null) return null;

    try {
      // GPS data biasanya dalam format: [degrees, minutes, seconds]
      if (gpsData is List && gpsData.length >= 3) {
        final degrees = _parseRational(gpsData[0]);
        final minutes = _parseRational(gpsData[1]);
        final seconds = _parseRational(gpsData[2]);

        if (degrees != null && minutes != null && seconds != null) {
          return degrees + (minutes / 60.0) + (seconds / 3600.0);
        }
      }

      // Jika sudah dalam format decimal
      if (gpsData is double) return gpsData;
      if (gpsData is int) return gpsData.toDouble();

      return null;
    } catch (e) {
      print('Error parsing GPS coordinate: $e');
      return null;
    }
  }

  /// Parse rational number (numerator/denominator)
  double? _parseRational(dynamic value) {
    if (value is double) return value;
    if (value is int) return value.toDouble();

    try {
      if (value is String) {
        if (value.contains('/')) {
          final parts = value.split('/');
          if (parts.length == 2) {
            final numerator = double.parse(parts[0]);
            final denominator = double.parse(parts[1]);
            if (denominator != 0) {
              return numerator / denominator;
            }
          }
        }
        return double.parse(value);
      }

      if (value is List && value.length == 2) {
        final numerator = value[0] as num;
        final denominator = value[1] as num;
        if (denominator != 0) {
          return numerator / denominator;
        }
      }
    } catch (e) {
      print('Error parsing rational: $e');
    }

    return null;
  }

  /// Validate GPS coordinates
  bool _isValidCoordinate(double? latitude, double? longitude) {
    if (latitude == null || longitude == null) return false;

    // Valid latitude: -90 to 90
    // Valid longitude: -180 to 180
    return latitude >= -90 &&
        latitude <= 90 &&
        longitude >= -180 &&
        longitude <= 180;
  }

  /// Get Indonesia region from coordinates (rough estimation)
  String? _getIndonesiaRegion(double latitude, double longitude) {
    // Rough boundaries untuk region Indonesia

    // Jakarta area
    if (latitude >= -6.3 &&
        latitude <= -6.0 &&
        longitude >= 106.7 &&
        longitude <= 107.0) {
      return 'Jakarta, DKI Jakarta';
    }

    // Surabaya area
    if (latitude >= -7.5 &&
        latitude <= -7.0 &&
        longitude >= 112.5 &&
        longitude <= 113.0) {
      return 'Surabaya, Jawa Timur';
    }

    // Malang area
    if (latitude >= -8.2 &&
        latitude <= -7.8 &&
        longitude >= 112.5 &&
        longitude <= 112.8) {
      return 'Malang, Jawa Timur';
    }

    // Bandung area
    if (latitude >= -7.0 &&
        latitude <= -6.8 &&
        longitude >= 107.5 &&
        longitude <= 107.8) {
      return 'Bandung, Jawa Barat';
    }

    // Semarang area
    if (latitude >= -7.2 &&
        latitude <= -6.9 &&
        longitude >= 110.3 &&
        longitude <= 110.6) {
      return 'Semarang, Jawa Tengah';
    }

    // Yogyakarta area
    if (latitude >= -8.0 &&
        latitude <= -7.7 &&
        longitude >= 110.3 &&
        longitude <= 110.5) {
      return 'Yogyakarta, DI Yogyakarta';
    }

    // Bali area
    if (latitude >= -8.8 &&
        latitude <= -8.3 &&
        longitude >= 115.0 &&
        longitude <= 115.3) {
      return 'Denpasar, Bali';
    }

    // Medan area
    if (latitude >= 3.5 &&
        latitude <= 3.6 &&
        longitude >= 98.6 &&
        longitude <= 98.7) {
      return 'Medan, Sumatera Utara';
    }

    // Makassar area
    if (latitude >= -5.2 &&
        latitude <= -5.0 &&
        longitude >= 119.4 &&
        longitude <= 119.5) {
      return 'Makassar, Sulawesi Selatan';
    }

    // General regions based on coordinates
    if (latitude >= -9 &&
        latitude <= -5 &&
        longitude >= 106 &&
        longitude <= 115) {
      return 'Jawa'; // General Java region
    }

    if (latitude >= -9 &&
        latitude <= -8 &&
        longitude >= 115 &&
        longitude <= 116) {
      return 'Bali';
    }

    if (latitude >= 0 && latitude <= 6 && longitude >= 95 && longitude <= 106) {
      return 'Sumatera';
    }

    if (latitude >= -6 &&
        latitude <= 2 &&
        longitude >= 108 &&
        longitude <= 119) {
      return 'Kalimantan';
    }

    if (latitude >= -6 &&
        latitude <= 2 &&
        longitude >= 119 &&
        longitude <= 125) {
      return 'Sulawesi';
    }

    // Default: can't determine specific location
    return null;
  }

  /// Pick banner image
  Future<void> pickBannerImage(BuildContext context) async {
    try {
      final XFile? image = await _picker.pickImage(
        source: ImageSource.gallery,
        imageQuality: 85,
      );

      if (image != null) {
        isCompressing.value = true;
        final File imageFile = File(image.path);

        // Extract location from image metadata
        await extractLocationFromImage(imageFile);

        final compressed = await MediaCompressionService.compressImage(
          imageFile,
        );

        if (compressed != null) {
          bannerImage.value = compressed;
          // Clear existing banner when new one is uploaded
          existingBannerUrl.value = null;
          context.showSuccessSnackBar('Banner berhasil dipilih');
        }
        isCompressing.value = false;
      }
    } catch (e) {
      isCompressing.value = false;
      context.showErrorSnackBar('Gagal memilih gambar');
    }
  }

  /// Pick images (max 2 total)
  Future<void> pickImages(BuildContext context) async {
    try {
      final totalImages = existingImageUrls.length + images.length;

      if (totalImages >= 2) {
        context.showWarningSnackBar('Maksimal 2 gambar');
        return;
      }

      final List<XFile> pickedImages = await _picker.pickMultiImage(
        imageQuality: 85,
      );

      if (pickedImages.isNotEmpty) {
        isCompressing.value = true;

        for (var image in pickedImages) {
          final currentTotal = existingImageUrls.length + images.length;
          if (currentTotal >= 2) break;

          final File imageFile = File(image.path);

          // Extract location from first image if location is empty
          if (locationController.text.trim().isEmpty && images.isEmpty) {
            await extractLocationFromImage(imageFile);
          }

          final compressed = await MediaCompressionService.compressImage(
            imageFile,
          );

          if (compressed != null) {
            images.add(compressed);
          }
        }

        isCompressing.value = false;
        context.showSuccessSnackBar('${images.length} gambar dipilih');
      }
    } catch (e) {
      isCompressing.value = false;
      context.showErrorSnackBar('Gagal memilih gambar');
    }
  }

